#!/usr/bin/env bash
# Regenerate the tables in docs/DETECTORS.md and docs/DETECTION.md from the binary.
# usage: scripts/gen-docs.sh [path-to-ai-hooks]
set -euo pipefail
cd "$(dirname "$0")/.."
BIN="${1:-dist/ai-hooks}"
{
cat <<'EOF'
# Detectors

Generated by `scripts/gen-docs.sh` from `ai-hooks explain --markdown`. Each detector reports under its public name, `<REDACTED:name:fingerprint>`.
`ai-hooks explain NAME` prints one description; `ai-hooks rules list --json` is the machine-readable form.

The first version used shorter names. They are still accepted by `ai-hooks explain`, and `AI_HOOKS_PARITY=1` makes the binary emit them (together with the original detector set only), which is how it is checked against the Python implementation it descends from.

EOF
"$BIN" explain --markdown
echo
echo "## Old names"
echo
echo "| Old name | Public name |"
echo "|---|---|"
"$BIN" rules list --json | python3 -I -c '
import json, sys
d = json.load(sys.stdin)
for k, v in sorted(d["aliases"].items()):
    if k != v:
        print(f"| `{k}` | `{v}` |")
'
} > docs/DETECTORS.md
{
cat <<'EOF'
# Detection and false alarms on the bundled corpus

Generated by `scripts/gen-docs.sh` from `ai-hooks test --markdown`. The corpus (`corpus/`) holds **fake** secrets only: documented vendor examples and values generated from templates at test time. It is small and written by the authors, so this shows that each detector does what it says on its known shapes. It does not measure how the tool does on your data.

EOF
AI_HOOKS_CARDS=1 "$BIN" test --markdown
} > docs/DETECTION.md
echo "wrote docs/DETECTORS.md docs/DETECTION.md"
